export function cevirici(sozluk, dil) {
  const s = sozluk[dil] || sozluk.tr;
  return (anahtar, deger) => {
    let m = s[anahtar] ?? sozluk.tr[anahtar] ?? anahtar;
    if (deger) for (const [k, v] of Object.entries(deger)) m = m.split('{' + k + '}').join(String(v ?? ''));
    return m;
  };
}
